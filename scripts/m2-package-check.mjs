import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
const read = p => readFileSync(new URL(`../${p}`, import.meta.url), 'utf8');
const base = JSON.parse(read('app/src-tauri/tauri.conf.json'));
const win = JSON.parse(read('app/src-tauri/tauri.windows.conf.json'));
const mac = JSON.parse(read('app/src-tauri/tauri.macos.conf.json'));
assert.equal(base.productName, 'Embroidery Studio');
assert.equal(base.identifier, 'io.github.thomasttcryoo.embroiderystudio');
assert.equal(base.mainBinaryName, 'embroidery-studio');
assert.deepEqual(base.plugins.updater.endpoints, []);
assert.deepEqual(base.plugins['deep-link'].desktop.schemes, ['embroidery-studio']);
assert.equal(base.bundle.windows.webviewInstallMode.type, 'offlineInstaller');
assert.equal(base.bundle.windows.nsis.installMode, 'currentUser');
assert.deepEqual(win.bundle.fileAssociations, []);
assert(base.bundle.fileAssociations.every(a => a.rank === 'Alternate'));
assert(!base.bundle.fileAssociations.some(a => a.exportedType));
for (const c of [base, win, mac]) assert.equal(c.app.windows[0].title, 'Embroidery Studio');
assert(read('app/src-tauri/src/projects.rs').includes('FOLDER: &str = "Embroidery Studio"'));
assert(read('app/src-tauri/src/server/mod.rs').includes('PORT: u16 = 17842'));
assert(base.app.security.csp['connect-src'].includes('127.0.0.1:17842'));
assert(!base.app.security.csp['connect-src'].includes('17841'));
assert.match(read('app/src-tauri/src/updates.rs'), /pub fn configured\(\) -> bool \{[^}]*false/s);
const hooks = read('app/src-tauri/installer-hooks.nsh');
assert(hooks.includes('OpenWithProgids'));
assert(!/WriteRegStr HKCU "Software\\Classes\\\.[^"\\]+" ""/.test(hooks));
assert(!hooks.includes('DeleteRegKey HKCU "Software\\Classes\\.'));
assert(!hooks.includes('Kadwood'));
const workflow = read('.github/workflows/release.yml');
assert(!workflow.includes('contents: write'));
assert(!workflow.includes('gh release'));
assert(!workflow.includes('tags:'));
assert(workflow.includes('macos-14'));
assert(workflow.includes('timeout-minutes: 80'));
const protectedDiff = execFileSync('git', ['diff', '6334c8b', '--', 'engine', 'editor/src/state', 'editor/src/project', 'editor/src/platform', 'editor/src/studio.css'], { encoding: 'utf8' });
assert.equal(protectedDiff, '', 'M1 engine, editing, file/project implementation and interface CSS must remain unchanged');
console.log('PASS: separate identity, offline runtime, non-default associations, isolated bridge/projects, disabled updates, private-only workflow and protected M1 sources.');
